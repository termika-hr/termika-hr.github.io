const DIRS_HR = {
  N: 'S', NNE: 'SSI', NE: 'SI', ENE: 'ISI', E: 'I', ESE: 'IJI', SE: 'JI', SSE: 'JJI',
  S: 'J', SSW: 'JJZ', SW: 'JZ', WSW: 'ZJZ', W: 'Z', WNW: 'ZSZ', NW: 'SZ', NNW: 'SSZ',
};

export function dirLabel(code, lang) {
  return lang === 'hr' ? DIRS_HR[code] || code : code;
}

const POINTS = ['N', 'NNE', 'NE', 'ENE', 'E', 'ESE', 'SE', 'SSE', 'S', 'SSW', 'SW', 'WSW', 'W', 'WNW', 'NW', 'NNW'];
export function degLabel(deg, lang) {
  return dirLabel(POINTS[Math.round((((deg % 360) + 360) % 360) / 22.5) % 16], lang);
}

